"""
parity/make_maple.py -- write qseries_battery.mpl from parity/cases.py.

Usage (repo root):  python3 parity/make_maple.py      -> parity/qseries_battery.mpl

Garvan runs it in Maple with the qseries package installed:
    read "qseries_battery.mpl";
It writes maple_results.txt (one line per case: id <TAB> result <TAB> seconds) in Maple's
current directory. A case that raises an error is logged as ERROR and the run continues.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from parity.cases import CASES, MAPLE_PRELUDE, SEED  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "qseries_battery.mpl")

HEADER = r'''# qseries_battery.mpl -- Maple-parity battery for qseries-sage (generated by parity/make_maple.py; seed %d)
# Run in Maple with Garvan's qseries package available:   read "qseries_battery.mpl";
# Output: maple_results.txt in the current directory (see currentdir()). About %d cases.
interface(warnlevel = 0):
with(qseries):
%s
fd := fopen("maple_results.txt", WRITE, TEXT):
fprintf(fd, "# maple\t%%s\n", StringTools:-SubstituteAll(convert(kernelopts(version), string), "\n", " ")):
try fprintf(fd, "# qseries\t%%s\n", StringTools:-SubstituteAll(sprintf("%%a", [packageversion()]), "\n", " ")) catch: fprintf(fd, "# qseries\t?\n") end try:
fprintf(fd, "# seed\t%d\n"):
WR := proc(id, t) local r; r := [args[3 .. -1]]; r := `if`(nops(r) = 0, NULL_RESULT, `if`(nops(r) = 1, r[1], r)); fprintf(fd, "%%s\t%%s\t%%.2f\n", id, StringTools:-SubstituteAll(StringTools:-SubstituteAll(StringTools:-SubstituteAll(sprintf("%%a", r), "\n", ""), "\t", " "), "NULL_RESULT", "NULL"), time() - t) end proc:
WE := proc(id, t) fprintf(fd, "%%s\tERROR %%s\t%%.2f\n", id, StringTools:-SubstituteAll(StringTools:-FormatMessage(lastexception[2 .. -1]), "\n", " "), time() - t) end proc:
'''

CASE_TMPL = r'''t0 := time():
try {setup}res := {expr}: WR("{id}", t0, res) catch: WE("{id}", t0) end try:
'''

FOOTER = r'''fclose(fd):
printf("qseries battery finished: results in %s\n", cat(currentdir(), kernelopts(dirsep), "maple_results.txt")):
'''


def main():
    parts = [HEADER % (SEED, len(CASES), MAPLE_PRELUDE.strip(), SEED)]
    for c in CASES:
        setup = (c.maple_setup.strip().rstrip(":;") + ": ") if c.maple_setup.strip() else ""
        parts.append("# %s (%s)\n" % (c.id, c.kind) + CASE_TMPL.format(id=c.id, expr=c.maple, setup=setup))
    parts.append(FOOTER)
    with open(OUT, "w", encoding="ascii") as fh:
        fh.write("\n".join(parts))
    print("wrote %s (%d cases)" % (OUT, len(CASES)))


if __name__ == "__main__":
    main()
